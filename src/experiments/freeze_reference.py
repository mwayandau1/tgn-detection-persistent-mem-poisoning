"""
Freeze every reported figure into one file, so nothing has to be typed into a notebook again.

WHY THIS EXISTS

A reproduction notebook needs a reference. Printing a computed 0.80 tells a reader nothing
unless they already know what it should be, so each result cell has to show what was reported
alongside what was just measured. That need is real.

The wrong way to serve it, which this replaces, is to type the reference into the notebook
cell as a literal. Doing that across three notebooks produced 115 hardcoded four-decimal
numbers, none of which the code could check, all of which had to be kept in sync by hand, and
every one of them a duplicate of a value already sitting in a committed JSON artefact. It is
the same defect the notebooks were rewired to remove when they re-implemented src/: a second
copy of the truth that nothing keeps honest.

WHY A FROZEN SNAPSHOT AND NOT THE LIVE ARTEFACTS

Reading experiments/run_burst2k_base/sequence_eval.json directly would be worse than useless
the moment anyone retrains: the run overwrites that file, so the "expected" column would be
the same number as the "measured" column by construction and the comparison would always
agree. That is a check that cannot fail, which is not a check.

So this harvests the artefacts once and writes experiments/reported_results.json, which is
COMMITTED and then left alone. It is the record of what the thesis claims. Retraining changes
the live artefacts and leaves the reference untouched, so the notebooks show a real delta.

Regenerate it only when the reported figures are meant to change -- that is, when the thesis
is being updated to new numbers -- and say so in the commit message, because regenerating it
silently is how a reference stops meaning anything.

Usage:
    python -m src.experiments.freeze_reference
    python -m src.experiments.freeze_reference --check   # verify, write nothing
"""

import argparse
import json
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT))

DATA = ROOT / "data" / "raw" / "ap_burst2k"
EXP = ROOT / "experiments"

# Every ablation run, with the label the thesis uses for it.
RUNS = {
    "attention readout (baseline)": "run_burst2k_base",
    "seed 1": "run_burst2k_base_s1",
    "gated readout": "run_burst2k_gated",
    "mean-pool readout": "run_burst2k_meanpool",
    "no structural features": "run_burst2k_nostruct",
    "temporal removed (attention)": "run_burst2k_static_attn",
    "temporal removed (mean)": "run_burst2k_static_mean",
}


def load(path):
    try:
        return json.load(open(path))
    except (OSError, json.JSONDecodeError):
        return None


def harvest():
    out = {
        "_comment": "Frozen reference: the figures as reported in the thesis. Generated by "
                    "src/experiments/freeze_reference.py from the run artefacts. Notebooks "
                    "read their 'expected' column from here rather than hardcoding it. Do NOT "
                    "regenerate casually -- retraining should show a delta against this file, "
                    "not silently overwrite it.",
        "generated": date.today().isoformat(),
        "benchmark": "ap_burst2k",
        "missing": [],
    }
    try:
        out["commit"] = subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True).strip()
    except Exception:
        out["commit"] = None

    # --- dataset ------------------------------------------------------------------------
    meta, splits = load(DATA / "metadata.json"), load(DATA / "splits.json")
    if meta and splits:
        m = {x["sequence_id"]: x for x in meta}
        out["dataset"] = {"n_sequences": len(m),
                          "n_poisoned": sum(1 for v in m.values() if v["label"] == "poisoned")}
        for name in ("train", "val", "test"):
            ids = splits[name]
            p = sum(1 for i in ids if m[i]["label"] == "poisoned")
            out["dataset"][name] = {"sequences": len(ids), "poisoned": p,
                                    "windows": len(ids) * 11}
    else:
        out["missing"].append("dataset metadata/splits")

    # --- sequence level, every run ------------------------------------------------------
    out["sequence_level"] = {}
    for label, run in RUNS.items():
        se = load(EXP / run / "sequence_eval.json")
        if not se:
            out["missing"].append(f"{run}/sequence_eval.json")
            continue
        for name, v in se["models"].items():
            # sequence_eval recomputes the regression baselines in EVERY run directory, so
            # take those from the baseline run only and keep each run's own model rows.
            is_baseline_row = name in ("final-state features (6)", "temporal features (7)",
                                       "all features (13)")
            if is_baseline_row and run != "run_burst2k_base":
                continue
            out["sequence_level"][name] = {"auroc": v["auroc"], "ap": v["ap"],
                                           "ci95": v["ci95"], "run": run}
        out.setdefault("runs", {})[label] = run

    # The unsupervised detectors are scored on the same 500 sequences as everything else, so
    # they belong in the same lookup. Filed only under "unsupervised" they were invisible to
    # the notebooks' reference column, which printed "(no reference)" for a figure that was
    # sitting in the file two keys away.
    us = load(DATA / "unsupervised_baselines.json")
    if us:
        for name, v in us.get("sequence_level", {}).items():
            out["sequence_level"][name] = {"auroc": v["auroc"], "ap": v["ap"],
                                           "ci95": v.get("ci95"),
                                           "run": "unsupervised_baselines"}

    # --- paired deltas, detector against every other model ------------------------------
    # sequence_eval records only the delta against the strongest hand-built baseline, but the
    # notebooks compare the detector against all of them. Computing these here keeps every
    # reference figure derived from the scores rather than typed into a cell.
    try:
        import numpy as np
        from src.experiments.sequence_eval import paired_boot

        base_npz = EXP / "run_burst2k_base" / "sequence_scores_test.npz"
        z = np.load(base_npz, allow_pickle=True)
        y, order = z["y"], z["sequence_id"]
        det_key = "T-GNN_baseline_(window_max)"
        det = z[det_key]

        sources = [(EXP / "run_burst2k_base" / "sequence_scores_test.npz", None)]
        for run in RUNS.values():
            if run != "run_burst2k_base":
                sources.append((EXP / run / "sequence_scores_test.npz", "static_GNN"))
        sources.append((DATA / "unsupervised_sequence_scores_test.npz", None))

        deltas, seen = {}, set()
        for path, filt in sources:
            if not path.exists():
                continue
            zz = np.load(path, allow_pickle=True)
            if not (zz["sequence_id"] == order).all():
                out["missing"].append(f"{path.name}: sequence order differs, skipped")
                continue
            for k in zz.files:
                if k in ("sequence_id", "y", det_key) or k in seen:
                    continue
                if filt and filt not in k and not k.startswith(("final-state", "temporal", "all_")):
                    continue
                if path.name == "sequence_scores_test.npz" and "run_burst2k_base" not in str(path) \
                        and k.startswith(("final-state", "temporal", "all_")):
                    continue          # each run bundles its own copy of the regressions
                seen.add(k)
                row = {}
                for metric in ("auroc", "ap"):
                    d, lo, hi = paired_boot(y, det, zz[k], 2000, metric=metric)
                    row[metric] = {"delta": d, "ci95": [lo, hi],
                                   "significant": bool(lo > 0 or hi < 0)}
                deltas[k.replace("_", " ")] = row
        out["paired_deltas"] = {"detector": det_key.replace("_", " "), "versus": deltas}
    except Exception as exc:                                   # noqa: BLE001
        out["missing"].append(f"paired deltas ({type(exc).__name__}: {exc})")

    # --- window level, training, latency ------------------------------------------------
    ev = load(EXP / "run_burst2k_base" / "eval_results.json")
    if ev:
        out["window_level"] = {"graph": ev.get("graph_level"), "node": ev.get("node_level"),
                               "detection_latency": ev.get("detection_latency")}
    else:
        out["missing"].append("run_burst2k_base/eval_results.json")

    th = load(EXP / "run_burst2k_base" / "training_history.json")
    if th:
        out["training"] = {"val_auroc": th["val_auroc"],
                           "val_node_auroc": th["val_node_auroc"],
                           "selection": th["selection"]}
    else:
        out["missing"].append("run_burst2k_base/training_history.json")

    lat = load(EXP / "run_burst2k_base" / "latency_matched_fpr.json")
    if lat:
        out["latency_matched_fpr"] = lat
    else:
        out["missing"].append("run_burst2k_base/latency_matched_fpr.json")

    # --- probes, gate, unsupervised, leak diagnosis --------------------------------------
    for key, path in (("probes", DATA / "separability_probe.json"),
                      ("benchmark_gate", DATA / "benchmark_gate.json"),
                      ("unsupervised", DATA / "unsupervised_baselines.json"),
                      ("leak_diagnosis", ROOT / "data/raw/llm_generated/leak_mechanism.json")):
        v = load(path)
        if v:
            out[key] = v
        else:
            out["missing"].append(str(path.relative_to(ROOT)))

    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="Report what would change without writing.")
    ap.add_argument("--output", default=str(EXP / "reported_results.json"))
    args = ap.parse_args()

    fresh = harvest()
    out = Path(args.output)

    print(f"harvested {len(fresh.get('sequence_level', {}))} sequence-level results "
          f"from {len(fresh.get('runs', {}))} runs")
    for k in ("window_level", "training", "latency_matched_fpr", "probes",
              "benchmark_gate", "unsupervised", "leak_diagnosis"):
        print(f"  {k:<22} {'ok' if k in fresh else 'MISSING'}")
    if fresh["missing"]:
        print(f"\n  {len(fresh['missing'])} artefact(s) not found:")
        for m in fresh["missing"]:
            print(f"    {m}")

    if args.check:
        old = load(out)
        if old is None:
            print(f"\n{out.name} does not exist yet -- run without --check to create it")
            return
        drift = []
        for name, v in fresh.get("sequence_level", {}).items():
            o = old.get("sequence_level", {}).get(name)
            if o is None:
                drift.append(f"  NEW    {name}: {v['auroc']:.4f}")
            elif abs(o["auroc"] - v["auroc"]) > 1e-9:
                drift.append(f"  MOVED  {name}: {o['auroc']:.4f} -> {v['auroc']:.4f} "
                             f"({v['auroc'] - o['auroc']:+.4f})")
        for name in old.get("sequence_level", {}):
            if name not in fresh.get("sequence_level", {}):
                drift.append(f"  GONE   {name}")
        print(f"\nagainst the frozen reference ({out.name}, commit {old.get('commit')}):")
        print("\n".join(drift) if drift else "  identical -- nothing has moved")
        return

    out.parent.mkdir(parents=True, exist_ok=True)
    json.dump(fresh, open(out, "w"), indent=2)
    print(f"\nwrote {out}")
    print("This file is the reference the notebooks compare against. Commit it, and do not")
    print("regenerate it unless the reported figures are meant to change.")


if __name__ == "__main__":
    main()
